export const generateSeatsLayout = (pricing = { Silver: 220, Gold: 380, VIP: 550 }) => {
  const seats = [];
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];
  const cols = 10;

  rows.forEach((row, rowIndex) => {
    let tier = 'Gold';
    let price = pricing.Gold || 380;

    if (rowIndex <= 1) {
      tier = 'Silver';
      price = pricing.Silver || 220;
    } else if (rowIndex >= 6) {
      tier = 'VIP';
      price = pricing.VIP || 550;
    }

    for (let c = 1; c <= cols; c++) {
      seats.push({
        seatNumber: `${row}${c}`,
        row,
        col: c,
        tier,
        price,
        status: 'available',
        lockedBy: null,
        lockExpiresAt: null,
      });
    }
  });

  return seats;
};

export const getFutureDates = (count = 5) => {
  const dates = [];
  for (let i = 0; i < count; i++) {
    const d = new Date();
    d.setDate(d.getDate() + i);
    dates.push(d.toISOString().split('T')[0]);
  }
  return dates;
};

export const generateInitialShows = () => {
  const dates = getFutureDates(4);
  const times = ['10:00 AM', '01:30 PM', '05:00 PM', '08:45 PM', '11:15 PM'];
  const shows = [];
  let idCounter = 1;

  initialTheatres.forEach((theatre) => {
    dates.forEach((date, dateIdx) => {
      initialMovies.slice(0, 4).forEach((movie, movieIdx) => {
        const time = times[(movieIdx + dateIdx) % times.length];
        const pricing = {
          Silver: theatre.city === 'Mumbai' ? 240 : 200,
          Gold: theatre.city === 'Mumbai' ? 400 : 350,
          VIP: theatre.city === 'Mumbai' ? 600 : 520,
        };

        const seats = generateSeatsLayout(pricing);

        if (dateIdx === 0 && movieIdx === 0) {
          const s1 = seats.find((s) => s.seatNumber === 'C4');
          const s2 = seats.find((s) => s.seatNumber === 'C5');
          if (s1) s1.status = 'booked';
          if (s2) s2.status = 'booked';
        }

        shows.push({
          _id: `show_${idCounter++}`,
          movie: movie._id,
          theatre: theatre._id,
          screenNumber: 1,
          date,
          startTime: time,
          endTime: 'Approx 2h 45m',
          format: movie.formats?.[0] || 'IMAX 3D',
          language: movie.language,
          pricing,
          seats,
          isActive: true,
        });
      });
    });
  });

  return shows;
};
